public class twodArrays {
   public static void main (String[] args){
        int nums[][] ={{1,3,5},{1,2},{1,3}};
        for(int i=0;i<=2;i++){
            for(int j =0; j<nums[i].length;j++){
                System.out.println(nums[i][j]);

            }
            System.out.println();
        }
   }
        
}

